def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--exclude-arms", nargs="*", default=[],
                    help="arm ids to leave out (e.g. an arm whose sweep is incomplete)")
    ap.add_argument("--require-seeds", type=int, default=None,
                    help="drop any (arm, split, n) cell with fewer than this many seeds")
    args = ap.parse_args()

    df = load()
    if args.exclude_arms:
        df = df[~df.arm.isin(args.exclude_arms)]
        print(f"excluded arms: {args.exclude_arms}")
    if args.require_seeds:
        counts = df.groupby(["arm", "split", "n_train"])["seed"].transform("count")
        dropped = sorted(df[counts < args.require_seeds].arm.unique())
        df = df[counts >= args.require_seeds]
        if dropped:
            print(f"dropped cells with <{args.require_seeds} seeds from: {dropped}")
    inputs = f"results/metrics/*.json ({len(df)} records)"
    print(f"loaded {len(df)} metric records; arms={sorted(df.arm.unique())}")

    for split in sorted(df.split.unique()):
        write_csv(table_learning_curves(df, split),
                  TABLES / f"table1_learning_curves__{split}.csv", inputs)
        der = table_der(df, split)
        if not der.empty:
            write_csv(der, TABLES / f"table2_der__{split}.csv", inputs, index=False)
        paired = table_paired(df, split)
        if not paired.empty:
            write_csv(paired, TABLES / f"table3_paired_tests__{split}.csv", inputs, index=False)
        figure_learning_curves(df, split)
        figure_ranking_curves(df, split)

    if df.split.nunique() > 1:
        write_csv(table_split_difficulty(df),
                  TABLES / "table4_split_difficulty.csv", inputs, index=False)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
